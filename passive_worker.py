import asyncio
import httpx
import logging

logger = logging.getLogger(__name__)

async def start_passive_learning_worker(learning_queue: asyncio.Queue, draft_endpoints: list[str]):
    """Drains the learning queue and applies live adaptation payloads concurrently to the draft models on the APU node supervisor."""
    logger.info(f"Passive learning worker active. Live-adapting draft models at {draft_endpoints}.")
    async with httpx.AsyncClient(timeout=6000.0) as client: # Use a generous timeout for concurrent adaptation requests
        while True:
            try:
                payload = await learning_queue.get() # Block until a live payload is generated by the active session
                tasks = [client.post(f"{endpoint}/api/draft/adapt", json=payload) for endpoint in draft_endpoints] # Dispatch to all draft models concurrently without blocking the main event loop
                responses = await asyncio.gather(*tasks, return_exceptions=True)
                for i, response in enumerate(responses): # Check results to prevent silent failures
                    if isinstance(response, Exception): logger.error(f"Draft model {i} adaptation failed: {response}")
                    elif response.status_code != 200: logger.error(f"Draft model {i} rejected payload: {response.status_code} - {response.text}")
                logger.debug(f"Live adaptation applied to draft models. Queue size: {learning_queue.qsize()}")
            except asyncio.CancelledError:
                logger.info("Passive learning worker shutting down gracefully.")
                break
            except Exception as e:
                logger.error(f"Unexpected error in passive learning worker: {e}")
            finally:
                # Always mark task as done so the queue doesn't lock up
                learning_queue.task_done()



